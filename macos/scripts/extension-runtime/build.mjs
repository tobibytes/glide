#!/usr/bin/env node
// Build-time only: bundles entry.ts (+ the Electron app's src/extension-api runtimes) with esbuild from
// ../node_modules into one IIFE and embeds it in Sources/Features/Extensions/Runtime/ExtensionRuntimeJS.swift.
// The app itself never needs Node. Run after changing entry.ts or src/extension-api:
//   node macos/scripts/extension-runtime/build.mjs
import { createRequire } from "node:module";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const glideRoot = path.resolve(here, "../../..");
const require = createRequire(path.join(glideRoot, "package.json"));
const esbuild = require("esbuild");

const out = await esbuild.build({
  entryPoints: [path.join(here, "entry.ts")],
  bundle: true,
  format: "iife",
  platform: "neutral",
  target: "safari17",
  write: false,
  minify: false,
  legalComments: "none",
  logLevel: "warning",
});
const js = out.outputFiles[0].text;
const hash = crypto.createHash("sha256").update(js).digest("hex").slice(0, 16);
let fence = "#";
while (js.includes(`"""${fence}`) || js.includes(`\\${fence}`)) fence += "#";
const swift = `// GENERATED by macos/scripts/extension-runtime/build.mjs — do not edit. Source: entry.ts + src/extension-api.
// swiftlint:disable all
enum ExtensionRuntimeJS {
    static let hash = "${hash}"
    static let source = ${fence}"""
${js}
"""${fence}
}
`;
const dest = path.join(glideRoot, "macos/Sources/Features/Extensions/Runtime/ExtensionRuntimeJS.swift");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, swift);
console.log(`wrote ${path.relative(glideRoot, dest)} (${js.length} bytes, ${hash})`);
