#!/bin/bash
# Embeds the Glide Remote web app (Sources/Features/Phone/Web/*) into Sources/Features/Phone/PhoneWebAssets.swift.
# Text files become Swift raw string literals; binary files (the icon) become base64 decoded at load.
# The output is deterministic (sorted paths, no timestamps). Run it after editing anything in Web/.
#
#   scripts/embed-phone-web.sh           regenerate PhoneWebAssets.swift
#   scripts/embed-phone-web.sh --check   exit 1 if PhoneWebAssets.swift is out of date (used by PhoneWebTests)
set -euo pipefail
cd "$(dirname "$0")/.."
WEB="Sources/Features/Phone/Web"
OUT="Sources/Features/Phone/PhoneWebAssets.swift"

generate() {
  python3 -I - "$WEB" <<'PY'
import base64, os, sys
web = sys.argv[1]
TYPES = {
    ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
    ".json": "application/json", ".webmanifest": "application/manifest+json", ".svg": "image/svg+xml", ".txt": "text/plain; charset=utf-8",
    ".png": "image/png", ".ico": "image/x-icon", ".jpg": "image/jpeg",
}
BINARY = {".png", ".ico", ".jpg"}
text, binary = [], []
for name in sorted(os.listdir(web)):
    path = os.path.join(web, name)
    if name.startswith(".") or not os.path.isfile(path):
        continue
    ext = os.path.splitext(name)[1].lower()
    if ext not in TYPES:
        sys.exit(f"embed-phone-web: no content type for {name}")
    route = "/" if name == "index.html" else "/" + name
    data = open(path, "rb").read()
    if ext in BINARY:
        binary.append((route, TYPES[ext], base64.b64encode(data).decode("ascii")))
    else:
        s = data.decode("utf-8")
        if "\r" in s:
            sys.exit(f"embed-phone-web: {name} has CR line endings")
        text.append((route, TYPES[ext], s))

def raw(s):
    n = 1
    while ('"""' + "#" * n) in s or ("\\" + "#" * n) in s:
        n += 1
    h = "#" * n
    return h + '"""\n' + s + '\n"""' + h

out = ["import Foundation", "",
       "/// GENERATED by scripts/embed-phone-web.sh from Sources/Features/Phone/Web/. Do not edit by hand.",
       "/// path (\"/\", \"/app.js\", …) → (content type, body). phone-core serves these unauthenticated (code only, no data).",
       "/// Text assets are in `files`, binary ones (the icon) in `binary`; `asset(_:)` returns either as bytes.",
       "enum PhoneWebAssets {",
       "    static let files: [String: (type: String, body: String)] = ["]
for route, typ, s in text:
    out.append(f'        "{route}": ("{typ}", {raw(s)}),')
out.append("    ]")
out.append("")
out.append("    static let binary: [String: (type: String, base64: String)] = [")
for route, typ, b in binary:
    out.append(f'        "{route}": ("{typ}", "{b}"),')
out.append("    ]")
out.append("""
    /// The asset for a request path ("/index.html" is "/"), as bytes. nil when there is none.
    static func asset(_ path: String) -> (type: String, data: Data)? {
        let p = path == "/index.html" ? "/" : path
        if let f = files[p] { return (f.type, Data(f.body.utf8)) }
        if let b = binary[p], let d = Data(base64Encoded: b.base64) { return (b.type, d) }
        return nil
    }
}""")
sys.stdout.write("\n".join(out) + "\n")
PY
}

if [[ "${1:-}" == "--check" ]]; then
  tmp="$(mktemp)"
  trap 'rm -f "$tmp"' EXIT
  generate > "$tmp"
  if cmp -s "$tmp" "$OUT"; then echo "PhoneWebAssets.swift is up to date"; else echo "PhoneWebAssets.swift is out of date: run scripts/embed-phone-web.sh" >&2; exit 1; fi
else
  generate > "$OUT.tmp"
  mv "$OUT.tmp" "$OUT"
  echo "Wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
fi
