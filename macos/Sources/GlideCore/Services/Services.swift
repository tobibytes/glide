import CoreGraphics
import Foundation

// Interfaces to the operating system. Features depend ONLY on these protocols; GlideSystem provides the real
// AppKit implementations (absorbed from the old glide-helper) and the headless fakes used by every test run.
// Everything is main-actor bound; methods that can block (Accessibility, AppleScript, Vision) are async and
// do their work off the main thread internally.

/// A running application (helper `Apps.describe`).
public struct RunningAppInfo: Hashable, Codable, Sendable {
    public var name: String
    public var bundleId: String?
    public var pid: Int32
    public var path: String?
    public init(name: String, bundleId: String?, pid: Int32, path: String?) {
        self.name = name
        self.bundleId = bundleId
        self.pid = pid
        self.path = path
    }
}

/// Generic ok/error outcome for helper-style commands.
public struct ServiceResult: Hashable, Codable, Sendable {
    public var ok: Bool
    public var error: String?
    public init(ok: Bool, error: String? = nil) {
        self.ok = ok
        self.error = error
    }
    public static let success = ServiceResult(ok: true)
    public static func failure(_ m: String) -> ServiceResult { ServiceResult(ok: false, error: m) }
}

// MARK: - launching / side effects

@MainActor public protocol WorkspaceService: AnyObject {
    /// Open a URL with its default handler (or `withApp`: bundle path or bundle id).
    func open(url: URL, withApp: String?) -> ServiceResult
    /// Open a file, folder or .app bundle.
    func open(path: String) -> ServiceResult
    /// Reveal in Finder.
    func reveal(path: String)
    /// Launch an application by name, bundle id or path.
    func launchApplication(_ nameOrBundleIdOrPath: String) -> ServiceResult
}

public extension WorkspaceService {
    func open(url: URL) -> ServiceResult { open(url: url, withApp: nil) }
}

@MainActor public protocol PasteboardService: AnyObject {
    func string() -> String?
    /// Write text (and optional HTML). `transient` marks it nspasteboard.org Transient/AutoGenerated so
    /// clipboard managers skip it.
    func setString(_ text: String, html: String?, transient: Bool)
    var changeCount: Int { get }
    /// The pasteboard's image as PNG data (any image type is converted), nil when there is none. (integration)
    func imagePNG() -> Data?
    /// Replace the contents with an image (PNG data).
    func setImagePNG(_ png: Data, transient: Bool)
    /// File URLs on the pasteboard (Finder copies), [] when none.
    func fileURLs() -> [URL]
    /// Replace the contents with file URLs (what Finder's ⌘C writes).
    func setFileURLs(_ urls: [URL])
}

public extension PasteboardService {
    func imagePNG() -> Data? { nil }
    func setImagePNG(_ png: Data, transient: Bool) {}
    func fileURLs() -> [URL] { [] }
    func setFileURLs(_ urls: [URL]) {}
}

/// Paste into the app behind the launcher. Because the launcher is a NON-ACTIVATING panel, the user's app is
