// MARK: - keyboard

public struct HotkeyBinding: Hashable, Sendable {
    public var id: String
    /// Electron-style accelerator ("Alt+Space", "Command+Space", "Double+Cmd", "⌥⌘K").
    public var accelerator: String
    public init(id: String, accelerator: String) {
        self.id = id
        self.accelerator = accelerator
    }
}

public struct HotkeyRegistration: Hashable, Codable, Sendable {
    public struct Failure: Hashable, Codable, Sendable {
        public var id: String
        public var reason: String
        public init(id: String, reason: String) {
            self.id = id
            self.reason = reason
        }
    }
    public var registered: [String]
    public var failed: [Failure]
    public var conflicts: [Failure]
    public init(registered: [String] = [], failed: [Failure] = [], conflicts: [Failure] = []) {
        self.registered = registered
        self.failed = failed
        self.conflicts = conflicts
    }
}

/// Global hotkeys: Carbon RegisterEventHotKey for combos, a listen-only tap for modifier-only shortcuts.
@MainActor public protocol HotkeyService: AnyObject {
    /// Replace all bindings. `onPress` receives the binding id.
    func set(_ bindings: [HotkeyBinding]) -> HotkeyRegistration
    var onPress: ((String) -> Void)? { get set }
    func unregisterAll()
}

public struct KeyboardTapConfig: Hashable, Sendable {
    public struct SnippetEntry: Hashable, Sendable {
        public var keyword: String
        public var text: String
        public var id: String?
        public var excludedBundleIds: [String]
        public init(keyword: String, text: String, id: String? = nil, excludedBundleIds: [String] = []) {
            self.keyword = keyword
            self.text = text
            self.id = id
            self.excludedBundleIds = excludedBundleIds
        }
    }
    public var snippets: [SnippetEntry] = []
    public var hyperKey = false
    public var pasteStack = false
    public var excludedBundleIds: [String] = []
    public init() {}
}

/// Events from the keyboard tap (were "snippet.matched", "stack.next", "snippet.expanded", "keys.tapFailed").
public enum KeyboardTapEvent: Sendable {
    case snippetMatched(reqId: Int, keyword: String, id: String, bundleId: String?)
    case snippetExpanded(keyword: String, live: Bool)
    case stackNext(reqId: Int)
    case tapFailed(reason: String)
}

/// Snippet expansion, the ⌘V Paste Stack and the Hyper key (event tap + KeysLogic).
@MainActor public protocol KeyboardTapService: AnyObject {
    /// Returns an error message when the tap could not be created.
    func configure(_ config: KeyboardTapConfig) -> String?
    var onEvent: ((KeyboardTapEvent) -> Void)? { get set }
    @discardableResult func finishExpansion(reqId: Int, text: String?, html: String?, cursorLeft: Int?) -> Bool
    @discardableResult func applyStackReply(reqId: Int, text: String?, html: String?, passthrough: Bool, empty: Bool, active: Bool?) -> Bool
    func shutdown()
}

// MARK: - permissions and misc system data

public struct PermissionsStatus: Hashable, Codable, Sendable {
    public var accessibility: Bool
    public var inputMonitoring: Bool
    /// "authorized" | "denied" | "restricted" | "notDetermined"
    public var calendar: String
    public var reminders: String
    public var location: String
    public init(accessibility: Bool, inputMonitoring: Bool, calendar: String, reminders: String, location: String) {
        self.accessibility = accessibility
        self.inputMonitoring = inputMonitoring
        self.calendar = calendar
        self.reminders = reminders
        self.location = location
    }
}

public enum PermissionKind: String, Sendable, CaseIterable { case accessibility, inputMonitoring, calendar, reminders, location }

@MainActor public protocol PermissionService: AnyObject {
    /// Never prompts.
    func status() -> PermissionsStatus
    /// Shows the system prompt — ONLY from an explicit user action.
    func request(_ kind: PermissionKind) async -> PermissionsStatus
    /// Polled every 2 s (permissions have no change notification).
    var onChange: ((PermissionsStatus) -> Void)? { get set }
}

/// A rectangle as plain numbers (Hashable/Codable, unlike CGRect).
public struct Rect: Hashable, Codable, Sendable {
    public var x: Double, y: Double, width: Double, height: Double
    public init(x: Double, y: Double, width: Double, height: Double) {
        self.x = x
        self.y = y
        self.width = width
        self.height = height
    }
    public init(_ r: CGRect) { self.init(x: Double(r.minX), y: Double(r.minY), width: Double(r.width), height: Double(r.height)) }
    public var cgRect: CGRect { CGRect(x: x, y: y, width: width, height: height) }
}

