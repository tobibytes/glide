/// Everything a feature can ask of the OS. Built once by the app (real or headless).
@MainActor public final class SystemServices {
    public let workspace: any WorkspaceService
    public let pasteboard: any PasteboardService
    public let paste: any PasteService
    public let notifications: any NotificationService
    public let scripts: any ScriptService
    public let confirmation: any ConfirmationService
    public let frontmost: any FrontmostAppService
    public let selection: any SelectionService
    public let windows: any WindowService
    public let menus: any MenuService
    public let hotkeys: any HotkeyService
    public let keyboardTap: any KeyboardTapService
    public let permissions: any PermissionService
    public let ocr: any OCRService
    public let eventKit: any EventKitService
    public let finder: any FinderService
    public let wifi: any WiFiService
    public let colorPicker: any ColorPickerService
    public let layouts: any LayoutService
    public let spotlight: any SpotlightShortcutService
    /// True in GLIDE_HEADLESS mode: side effects are recorded, not performed.
    public let isHeadless: Bool

    public init(workspace: any WorkspaceService, pasteboard: any PasteboardService, paste: any PasteService,
                notifications: any NotificationService, scripts: any ScriptService, confirmation: any ConfirmationService,
                frontmost: any FrontmostAppService, selection: any SelectionService, windows: any WindowService,
                menus: any MenuService, hotkeys: any HotkeyService, keyboardTap: any KeyboardTapService,
                permissions: any PermissionService, ocr: any OCRService, eventKit: any EventKitService,
                finder: any FinderService, wifi: any WiFiService, colorPicker: any ColorPickerService,
                layouts: any LayoutService, spotlight: any SpotlightShortcutService, isHeadless: Bool) {
        self.workspace = workspace
        self.pasteboard = pasteboard
        self.paste = paste
        self.notifications = notifications
        self.scripts = scripts
        self.confirmation = confirmation
        self.frontmost = frontmost
        self.selection = selection
        self.windows = windows
        self.menus = menus
        self.hotkeys = hotkeys
        self.keyboardTap = keyboardTap
        self.permissions = permissions
        self.ocr = ocr
        self.eventKit = eventKit
        self.finder = finder
        self.wifi = wifi
        self.colorPicker = colorPicker
        self.layouts = layouts
        self.spotlight = spotlight
        self.isHeadless = isHeadless
    }
}
