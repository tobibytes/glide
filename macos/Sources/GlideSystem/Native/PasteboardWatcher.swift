import AppKit
import GlideCore

// Pasteboard watcher for Clipboard History (Clipboard 2.0). Owned by phase-1 session N2.
//
// The real watcher polls `NSPasteboard.general.changeCount` every 0.4 s on a background queue (one integer read per
// tick; content is only read when the count moved) and delivers a Sendable snapshot on the main actor. Writes made
// through the watcher record their change count so they are never captured again. In headless mode the factory hands
// out `FakePasteboardWatcher` (Headless/FakePasteboardWatcher.swift) instead: the real pasteboard is never touched.

/// One read of the general pasteboard.
public struct PasteboardSnapshot: Sendable, Equatable {
    public var changeCount: Int
    /// Raw pasteboard type identifiers (UTIs) of the first item and the pasteboard.
    public var types: [String]
    public var text: String?
    public var html: String?
    public var rtf: Data?
    /// Image bytes as PNG (TIFF and other bitmaps are converted).
    public var png: Data?
    /// Local file paths (file URLs).
    public var files: [String]
    /// "#RRGGBB" / "#RRGGBBAA" from an NSColor on the pasteboard.
    public var color: String?
    /// The app the user was working in when the change was seen.
    public var source: RunningAppInfo?

    public init(changeCount: Int = 0, types: [String] = [], text: String? = nil, html: String? = nil, rtf: Data? = nil, png: Data? = nil,
                files: [String] = [], color: String? = nil, source: RunningAppInfo? = nil) {
        self.changeCount = changeCount
        self.types = types
        self.text = text
        self.html = html
        self.rtf = rtf
        self.png = png
        self.files = files
        self.color = color
        self.source = source
    }
}

/// What to put on the pasteboard (one item). Files win over an image, an image over text.
public struct PasteboardContent: Sendable, Equatable {
    public var text: String?
    public var html: String?
    public var rtf: Data?
    public var png: Data?
    public var files: [String]
    public init(text: String? = nil, html: String? = nil, rtf: Data? = nil, png: Data? = nil, files: [String] = []) {
        self.text = text
        self.html = html
        self.rtf = rtf
        self.png = png
        self.files = files
    }
}

/// Watches and writes the general pasteboard (rich content: text, HTML, RTF, images, files, colors).
@MainActor public protocol PasteboardWatching: AnyObject {
    /// Called on the main actor for every change made by another app (never for our own writes).
    var onChange: ((PasteboardSnapshot) -> Void)? { get set }
    var isWatching: Bool { get }
    func start(interval: TimeInterval)
    func stop()
    /// Put content on the pasteboard (not transient: it stays there). Returns the new change count.
    @discardableResult func write(_ content: PasteboardContent) -> Int
    /// Write, then ⌘V into the app behind the (non-activating) launcher.
    func paste(_ content: PasteboardContent)
    /// The pasteboard right now.
    func read() async -> PasteboardSnapshot
}

/// Pasteboard type markers of secret or short-lived content (nspasteboard.org conventions).
public enum PasteboardMarkers {
    public static let concealed = ["org.nspasteboard.concealedtype", "org.nspasteboard.transienttype", "org.nspasteboard.autogeneratedtype", "com.agilebits.onepassword"]
    public static func isConcealed(_ types: [String]) -> Bool {
        types.contains { t in
            let lower = t.lowercased()
            return concealed.contains { lower.contains($0) }
        }
    }
}

/// Change counts seen / written by us. Touched from the poll queue and the main actor.
final class PasteboardWatchState: @unchecked Sendable {
    private let lock = NSLock()
    private var last = Int.min
    private var ignored: [Int] = []

    /// True when `count` is a change we have not seen and did not make.
    func shouldRead(_ count: Int) -> Bool {
        lock.lock()
        defer { lock.unlock() }
        if count == last { return false }
        last = count
        return !ignored.contains(count)
    }

    func ignore(_ count: Int) {
        lock.lock()
        ignored.append(count)
        if ignored.count > 16 { ignored.removeFirst(ignored.count - 16) }
        lock.unlock()
    }
}

/// The real watcher. NEVER constructed in headless mode (see `PasteboardWatcherFactory`).
@MainActor public final class SystemPasteboardWatcher: PasteboardWatching {
    public var onChange: ((PasteboardSnapshot) -> Void)?
    public private(set) var isWatching = false
    private let queue = DispatchQueue(label: "dev.glide.pasteboard-watcher", qos: .utility)
    private var timer: DispatchSourceTimer?
    private let state = PasteboardWatchState()
    private let frontmost: (any FrontmostAppService)?
    /// Larger images are skipped (they would stall the poll queue and bloat history).
    nonisolated static let maxImageBytes = 64 * 1024 * 1024

    public init(frontmost: (any FrontmostAppService)?) { self.frontmost = frontmost }

    public func start(interval: TimeInterval) {
        guard timer == nil else { return }
        isWatching = true
        let state = self.state
        let t = DispatchSource.makeTimerSource(queue: queue)
        t.schedule(deadline: .now(), repeating: interval, leeway: .milliseconds(50))
        t.setEventHandler { [weak self] in
            let count = NSPasteboard.general.changeCount
            guard state.shouldRead(count) else { return }
            let snap = SystemPasteboardWatcher.readGeneral(changeCount: count)
            DispatchQueue.main.async { MainActor.assumeIsolated { self?.deliver(snap) } }
        }
        t.resume()
        timer = t
    }

    public func stop() {
        timer?.cancel()
        timer = nil
        isWatching = false
    }

    private func deliver(_ snap: PasteboardSnapshot) {
        var s = snap
        s.source = frontmost?.targetApp()
        onChange?(s)
    }

    @discardableResult
    public func write(_ content: PasteboardContent) -> Int {
        let pb = NSPasteboard.general
        pb.clearContents()
        if !content.files.isEmpty {
            pb.writeObjects(content.files.map { URL(fileURLWithPath: $0) as NSURL })
            pb.setString(content.files.joined(separator: "\n"), forType: .string)
        } else if let png = content.png {
            pb.setData(png, forType: .png)
            if let tiff = NSImage(data: png)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        } else {
            if let html = content.html, !html.isEmpty { pb.setString(html, forType: .html) }
            if let rtf = content.rtf, !rtf.isEmpty { pb.setData(rtf, forType: .rtf) }
            pb.setString(content.text ?? "", forType: .string)
        }
        let count = pb.changeCount
        state.ignore(count)
        return count
    }

    public func paste(_ content: PasteboardContent) {
        write(content)
        // The launcher panel was just ordered out: give the target app's field a moment to take key focus back.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { postKey(CGKeyCode(KeyCodes.v), flags: .maskCommand) }
    }

    public func read() async -> PasteboardSnapshot {
        let count = NSPasteboard.general.changeCount
        var s = await offMain { SystemPasteboardWatcher.readGeneral(changeCount: count) }
        s.source = frontmost?.targetApp()
        return s
    }

    /// Reads the general pasteboard. Concealed/transient content is reported by type only (never read).
    nonisolated static func readGeneral(changeCount: Int) -> PasteboardSnapshot {
        let pb = NSPasteboard.general
        var types = (pb.types ?? []).map(\.rawValue)
        for item in pb.pasteboardItems ?? [] { for t in item.types where !types.contains(t.rawValue) { types.append(t.rawValue) } }
        var s = PasteboardSnapshot(changeCount: changeCount, types: types)
        if PasteboardMarkers.isConcealed(types) { return s }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            s.files = urls.map(\.path)
        }
        s.text = pb.string(forType: .string)
        s.html = pb.string(forType: .html)
        s.rtf = pb.data(forType: .rtf)
        if types.contains(NSPasteboard.PasteboardType.color.rawValue), let c = NSColor(from: pb) { s.color = hex(c) }
        if s.files.isEmpty, s.text?.isEmpty ?? true {
            if let png = pb.data(forType: .png), png.count <= maxImageBytes {
                s.png = png
            } else if let tiff = pb.data(forType: .tiff), tiff.count <= maxImageBytes, let rep = NSBitmapImageRep(data: tiff) {
                s.png = rep.representation(using: .png, properties: [:])
            }
        }
        return s
    }

    nonisolated static func hex(_ color: NSColor) -> String? {
        guard let c = color.usingColorSpace(.sRGB) else { return nil }
        func b(_ v: CGFloat) -> String { String(format: "%02X", Int((max(0, min(1, v)) * 255).rounded())) }
        let base = "#" + b(c.redComponent) + b(c.greenComponent) + b(c.blueComponent)
        return c.alphaComponent < 0.999 ? base + b(c.alphaComponent) : base
    }
}

/// One watcher per `SystemServices` (real or fake, picked by headless mode).
@MainActor public enum PasteboardWatcherFactory {
    private struct Entry { weak var owner: SystemServices?; let watcher: any PasteboardWatching }
    private static var cache: [ObjectIdentifier: Entry] = [:]

    public static func watcher(for services: SystemServices) -> any PasteboardWatching {
        let key = ObjectIdentifier(services)
        // The weak owner check guards against a recycled address of a released services object.
        if let e = cache[key], e.owner === services { return e.watcher }
        let w: any PasteboardWatching
        if services.isHeadless || ProcessInfo.processInfo.environment["GLIDE_HEADLESS"] == "1" {
            w = FakePasteboardWatcher(base: services.pasteboard as? FakePasteboard, log: (services.pasteboard as? FakePasteboard)?.log ?? SideEffectLog(echo: false))
        } else {
            w = SystemPasteboardWatcher(frontmost: services.frontmost)
        }
        cache[key] = Entry(owner: services, watcher: w)
        return w
    }
}
