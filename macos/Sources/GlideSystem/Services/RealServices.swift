/// NSWorkspace launching. NEVER constructed in headless mode.
@MainActor public final class SystemWorkspaceService: WorkspaceService {
    public init() {}

    public func open(url: URL, withApp: String?) -> ServiceResult {
        guard let withApp, !withApp.isEmpty else { return NSWorkspace.shared.open(url) ? .success : .failure("Could not open \(url.absoluteString)") }
        let appURL = withApp.hasPrefix("/") ? URL(fileURLWithPath: withApp) : NSWorkspace.shared.urlForApplication(withBundleIdentifier: withApp)
        guard let appURL else { return .failure("App \(withApp) not found") }
        NSWorkspace.shared.open([url], withApplicationAt: appURL, configuration: NSWorkspace.OpenConfiguration())
        return .success
    }

    public func open(path: String) -> ServiceResult {
        let p = (path as NSString).expandingTildeInPath
        guard FileManager.default.fileExists(atPath: p) else { return .failure("\(p) does not exist") }
        let url = URL(fileURLWithPath: p)
        if p.hasSuffix(".app") {
            let cfg = NSWorkspace.OpenConfiguration()
            cfg.activates = true
            NSWorkspace.shared.openApplication(at: url, configuration: cfg)
            return .success
        }
        return NSWorkspace.shared.open(url) ? .success : .failure("Could not open \(p)")
    }

    public func reveal(path: String) { NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: (path as NSString).expandingTildeInPath)]) }

    public func launchApplication(_ app: String) -> ServiceResult {
        if app.hasPrefix("/") || app.hasPrefix("~") { return open(path: app) }
        if let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: app) { return open(path: url.path) }
        for dir in ["/Applications", "/System/Applications", "/System/Applications/Utilities", NSHomeDirectory() + "/Applications"] {
            let p = "\(dir)/\(app).app"
            if FileManager.default.fileExists(atPath: p) { return open(path: p) }
        }
        return .failure("App \(app) not found")
    }
}

@MainActor public final class SystemPasteboardService: PasteboardService {
    public init() {}
    public func string() -> String? { NSPasteboard.general.string(forType: .string) }
    public func setString(_ text: String, html: String?, transient: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let html, !html.isEmpty { pb.setString(html, forType: .html) }
        pb.setString(text, forType: .string)
        if transient {
            pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
    }
    public var changeCount: Int { NSPasteboard.general.changeCount }
    public func imagePNG() -> Data? {
        let pb = NSPasteboard.general
        if let png = pb.data(forType: .png) { return png }
        guard let image = NSImage(pasteboard: pb), let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
    public func setImagePNG(_ png: Data, transient: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setData(png, forType: .png)
        if transient { pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType")) }
    }
    public func fileURLs() -> [URL] {
        (NSPasteboard.general.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
    }
    public func setFileURLs(_ urls: [URL]) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.writeObjects(urls.map { $0 as NSURL })
    }
}

/// Paste-back: transient write, ⌘V, restore after 300 ms (helper Paste.swift).
@MainActor public final class SystemPasteService: PasteService {
    public init() {}
    public func paste(text: String, html: String?) {
        let pb = NSPasteboard.general
        let saved: [[(NSPasteboard.PasteboardType, Data)]] = (pb.pasteboardItems ?? []).map { item in item.types.compactMap { t in item.data(forType: t).map { (t, $0) } } }
        pb.clearContents()
        if let html, !html.isEmpty { pb.setString(html, forType: .html) }
        pb.setString(text, forType: .string)
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        let ours = pb.changeCount
        postKey(CGKeyCode(KeyCodes.v), flags: .maskCommand)
        let restoreAfter = PasteTiming.restoreDelay(bundleId: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreAfter) {
            guard pb.changeCount == ours else { return }
            pb.clearContents()
            guard !saved.isEmpty else { return }
            pb.writeObjects(saved.map { pairs -> NSPasteboardItem in
                let it = NSPasteboardItem()
                for (t, d) in pairs { it.setData(d, forType: t) }
                return it
            })
        }
    }
}

@MainActor public final class SystemNotificationService: NotificationService {
    public init() {}
    public func notify(title: String, body: String?) {
        let center = UNUserNotificationCenter.current()
        let content = UNMutableNotificationContent()
        content.title = title
        if let body { content.body = body }
        let request = UNNotificationRequest(identifier: UUID().uuidString, content: content, trigger: nil)
        center.getNotificationSettings { settings in
            if settings.authorizationStatus == .notDetermined {
                center.requestAuthorization(options: [.alert, .sound]) { ok, _ in if ok { center.add(request) } }
            } else {
                center.add(request)
            }
        }
    }
}

@MainActor public final class SystemScriptService: ScriptService {
    public init() {}

    public func runAppleScript(_ source: String) async throws -> String {
        let r = try await runShell("/usr/bin/osascript -e \(Self.shellQuote(source))", shell: "/bin/zsh", timeout: 30)
        if r.status != 0 { throw FeatureError.failed(r.stderr.trimmingCharacters(in: .whitespacesAndNewlines)) }
        return r.stdout.trimmingCharacters(in: .newlines)
    }

    public func runShell(_ command: String, shell: String, timeout: TimeInterval) async throws -> ShellResult {
        try await offMainThrowing {
            let p = Process()
            p.executableURL = URL(fileURLWithPath: shell)
            p.arguments = ["-c", command]
            let out = Pipe(), err = Pipe()
            p.standardOutput = out
            p.standardError = err
            try p.run()
            // Drain both pipes while the process runs: reading only after exit deadlocked once a command wrote
            // more than the 64 KB pipe buffer (integration fix).
            let ob = PipeDrain(out.fileHandleForReading), eb = PipeDrain(err.fileHandleForReading)
            let deadline = Date().addingTimeInterval(timeout)
            while p.isRunning && Date() < deadline { usleep(10_000) }
            if p.isRunning { p.terminate() }
            p.waitUntilExit()
            let o = ob.finish(), e = eb.finish()
            return ShellResult(status: p.terminationStatus, stdout: String(decoding: o, as: UTF8.self), stderr: String(decoding: e, as: UTF8.self))
        }
    }

    public nonisolated static func shellQuote(_ s: String) -> String { "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'" }
}

@MainActor public final class AlertConfirmationService: ConfirmationService {
    public init() {}
    public func confirm(title: String, message: String, confirmButton: String) async -> Bool {
        let alert = NSAlert()
        alert.messageText = message
        alert.informativeText = ""
        alert.addButton(withTitle: confirmButton)
        alert.addButton(withTitle: "Cancel")
        NSApp.activate(ignoringOtherApps: true)
        return alert.runModal() == .alertFirstButtonReturn
    }
}

/// How long paste-back keeps our text on the pasteboard before restoring the user's clipboard. Chromium /
/// Electron apps and a few others read the pasteboard late after ⌘V; restoring too early pastes the old
/// contents. (N4, pure; unit-tested.)
public enum PasteTiming {
    public static let standard: TimeInterval = 0.3
    public static let slow: TimeInterval = 0.8
    static let slowPrefixes = ["com.google.Chrome", "org.chromium.", "com.brave.Browser", "com.microsoft.", "company.thebrowser.", "com.vivaldi.",
                               "com.operasoftware.", "com.tinyspeck.slackmacgap", "com.hnc.Discord", "notion.id", "com.figma.", "md.obsidian",
                               "com.todesktop.", "com.electron.", "com.jetbrains.", "com.github.GitHubClient", "ai.perplexity.", "com.openai.chat"]

    public static func restoreDelay(bundleId: String?) -> TimeInterval {
        guard let id = bundleId else { return standard }
        return slowPrefixes.contains { id.hasPrefix($0) } ? slow : standard
    }
}

/// Reads a pipe to EOF on a background queue (so the writer never blocks on a full buffer). `finish` waits up to
/// 2 s after exit: a detached grandchild can keep the pipe open.
final class PipeDrain: @unchecked Sendable {
    private var data = Data()
    private let lock = NSLock()
    private let done = DispatchSemaphore(value: 0)
    init(_ handle: FileHandle) {
        DispatchQueue.global(qos: .userInitiated).async { [self] in
            let d = handle.readDataToEndOfFile()
            lock.lock(); data = d; lock.unlock()
            done.signal()
        }
    }
    func finish() -> Data {
        _ = done.wait(timeout: .now() + 2)
        lock.lock(); defer { lock.unlock() }
        return data
    }
}
