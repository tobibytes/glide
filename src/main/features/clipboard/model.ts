/** True while recording is off because of the pause toggle or a timed pause. */
export function isPaused(s: Pick<ClipSettings, "paused" | "pausedUntil">, now: number): boolean {
  return s.paused || s.pausedUntil > now;
}

/** Pasteboard types that mark content as secret or short-lived (nspasteboard.org conventions). */
export const CONCEALED_MARKERS = ["org.nspasteboard.concealedtype", "org.nspasteboard.transienttype", "org.nspasteboard.autogeneratedtype", "com.agilebits.onepassword"];

export function isConcealed(types: string[]): boolean {
  return types.some((t) => {
    const lower = t.toLowerCase();
    return CONCEALED_MARKERS.some((m) => lower.includes(m));
  });
}

export function isIgnoredApp(bundleId: string | null | undefined, ignored: string[]): boolean {
  if (!bundleId) return false;
  const id = bundleId.toLowerCase();
  return ignored.some((b) => b.trim().toLowerCase() === id);
}

const URL_RE = /^(https?:\/\/|mailto:|ftp:\/\/|file:\/\/)[^\s]+$/i;
const BARE_DOMAIN_RE = /^www\.[a-z0-9-]+(\.[a-z0-9-]+)+(\/[^\s]*)?$/i;
const HEX_RE = /^#(?:[0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
const FN_COLOR_RE = /^(rgba?|hsla?)\(\s*[-\d.%]+(deg)?\s*[,\s]\s*[-\d.%]+\s*[,\s]\s*[-\d.%]+\s*([,/]\s*[\d.%]+\s*)?\)$/i;

export function isColor(text: string): boolean {
  const t = text.trim();
  return HEX_RE.test(t) || FN_COLOR_RE.test(t);
}

export function isLink(text: string): boolean {
  const t = text.trim();
  return URL_RE.test(t) || BARE_DOMAIN_RE.test(t);
}

export function classifyText(text: string): "text" | "link" | "color" {
  if (isColor(text)) return "color";
  if (isLink(text)) return "link";
  return "text";
}

/** Parse a text/uri-list payload into local file paths (non-file URIs are ignored). */
export function filePathsFromUriList(uriList: string): string[] {
  const paths: string[] = [];
  for (const line of uriList.split(/\r?\n/)) {
    const l = line.trim();
    if (!l || l.startsWith("#") || !l.toLowerCase().startsWith("file://")) continue;
    try {
      paths.push(decodeURIComponent(new URL(l).pathname));
    } catch {
      /* malformed URI */
    }
  }
  return paths;
}

export function fileUrl(p: string): string {
  return "file://" + p.split("/").map(encodeURIComponent).join("/");
}

export function countWords(text: string): number {
  const m = text.trim().match(/\S+/g);
  return m ? m.length : 0;
}

/**
 * Insert a capture. Same key → existing entry moves to the top with count+1
 * (keeping its id, pin state and first-copied time). Returns the new list (newest first).
 */
export function upsert(entries: ClipEntry[], c: ClipCandidate, now: number, newId: () => string): { entries: ClipEntry[]; entry: ClipEntry; isNew: boolean } {
  const idx = entries.findIndex((e) => e.key === c.key);
  if (idx >= 0) {
    const prev = entries[idx]!;
    const entry: ClipEntry = { ...prev, lastCopiedAt: now, count: prev.count + 1, source: c.source ?? prev.source };
    const rest = entries.filter((_, i) => i !== idx);
    return { entries: [entry, ...rest], entry, isNew: false };
  }
  const entry: ClipEntry = { id: newId(), ...c, createdAt: now, lastCopiedAt: now, count: 1, pinned: false };
  return { entries: [entry, ...entries], entry, isNew: true };
}

/** Move an entry to the top (used after pasting/copying it from history). */
export function touch(entries: ClipEntry[], id: string, now: number): ClipEntry[] {
  const e = entries.find((x) => x.id === id);
  if (!e) return entries;
  return [{ ...e, lastCopiedAt: now, count: e.count + 1 }, ...entries.filter((x) => x !== e)];
}

export function sortEntries(entries: ClipEntry[]): ClipEntry[] {
  return [...entries].sort((a, b) => b.lastCopiedAt - a.lastCopiedAt);
}

const DAY = 86_400_000;

/**
 * Apply retention: age, entry count, image count and image bytes. Pinned entries are never removed.
 * Oldest unpinned entries go first. Returns kept and removed entries (caller deletes image files).
 */
export function prune(
  entries: ClipEntry[],
  s: Pick<ClipSettings, "retentionDays" | "maxEntries" | "maxImages" | "maxImageMB"> & { retentionByType?: Partial<Record<ClipType, number>> },
  now: number,
): { kept: ClipEntry[]; removed: ClipEntry[] } {
  const sorted = sortEntries(entries);
  const removed = new Set<ClipEntry>();
  const cutoffFor = (t: ClipType) => {
    const days = s.retentionByType?.[t] || s.retentionDays;
    return days > 0 ? now - days * DAY : -Infinity;
  };
  for (const e of sorted) if (!e.pinned && e.lastCopiedAt < cutoffFor(e.type)) removed.add(e);

  const alive = () => sorted.filter((e) => !removed.has(e));
  // Count cap: drop the oldest unpinned beyond maxEntries.
  let list = alive();
  if (s.maxEntries > 0 && list.length > s.maxEntries) {
    let excess = list.length - s.maxEntries;
    for (let i = list.length - 1; i >= 0 && excess > 0; i--) {
      if (!list[i]!.pinned) {
        removed.add(list[i]!);
        excess--;
      }
    }
  }
  // Image caps (count and total bytes), oldest unpinned images first.
  list = alive();
  const images = list.filter((e) => e.type === "image");
  let imgCount = images.length;
  let imgBytes = images.reduce((n, e) => n + (e.image?.bytes ?? 0), 0);
  const maxBytes = s.maxImageMB * 1024 * 1024;
  for (let i = images.length - 1; i >= 0; i--) {
    const overCount = s.maxImages > 0 && imgCount > s.maxImages;
    const overBytes = s.maxImageMB > 0 && imgBytes > maxBytes;
    if (!overCount && !overBytes) break;
    const e = images[i]!;
    if (e.pinned) continue;
    removed.add(e);
    imgCount--;
    imgBytes -= e.image?.bytes ?? 0;
  }
  return { kept: alive(), removed: [...removed] };
}

/** Searchable text for an entry. */
export function haystack(e: ClipEntry): string {
  const parts = [e.text ?? "", ...(e.files ?? []), e.source?.name ?? "", e.ocrText ?? ""];
  if (e.image) parts.push(`image ${e.image.width}x${e.image.height}`);
  return parts.join("\n").toLowerCase();
}

/** Source-app filter value: a bundle id, or "name:<app name>" when the bundle id is unknown. */
export const sourceKey = (src: SourceApp | null): string | null => (src ? (src.bundleId ?? `name:${src.name}`) : null);

export function matches(e: ClipEntry, query: string, filter: ClipFilter, hay: (e: ClipEntry) => string = haystack, source?: string | null): boolean {
  if (filter === "pinned" ? !e.pinned : filter !== "all" && e.type !== filter) return false;
  if (source && sourceKey(e.source) !== source) return false;
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return true;
  const h = hay(e);
  return words.every((w) => h.includes(w));
}

/** Pinned first, then most recently copied. */
export function filterEntries(entries: ClipEntry[], query: string, filter: ClipFilter, limit: number, hay?: (e: ClipEntry) => string, source?: string | null): ClipEntry[] {
  const out = entries.filter((e) => matches(e, query, filter, hay, source));
  out.sort((a, b) => Number(b.pinned) - Number(a.pinned) || b.lastCopiedAt - a.lastCopiedAt);
  return limit > 0 ? out.slice(0, limit) : out;
}

/** Display title (first non-empty line) for any entry. */
export function entryTitle(e: Pick<ClipEntry, "type" | "text" | "files" | "image">): string {
  if (e.type === "image" && e.image) return `Image (${e.image.width}×${e.image.height})`;
  if (e.type === "file" && e.files?.length) {
    const first = e.files[0]!.split("/").filter(Boolean).pop() ?? e.files[0]!;
    return e.files.length > 1 ? `${first} + ${e.files.length - 1} more` : first;
  }
  const line = (e.text ?? "").split(/\r?\n/).find((l) => l.trim()) ?? "";
  return line.trim().slice(0, 200) || "(whitespace)";
}

/** Lightweight shape sent to the renderer list (full text via get(id)). */
export interface ClipSummary {
  id: string;
  type: ClipType;
  title: string;
  /** First ~400 chars, for search highlighting / tooltips. */
  preview: string;
  files?: string[];
  image?: ClipImage;
  source: SourceApp | null;
  createdAt: number;
  lastCopiedAt: number;
  count: number;
  pinned: boolean;
  chars: number;
  words: number;
  /** Domain of a link entry ("github.com"). */
  domain?: string;
  /** Recognised image text (first ~400 chars). */
  ocr?: string;
}

export function summarize(e: ClipEntry): ClipSummary {
  const text = e.text ?? "";
  return {
    id: e.id,
    type: e.type,
    title: entryTitle(e),
    preview: text.slice(0, 400),
    files: e.files,
    image: e.image,
    source: e.source,
    createdAt: e.createdAt,
    lastCopiedAt: e.lastCopiedAt,
    count: e.count,
    pinned: e.pinned,
    chars: text.length,
    words: countWords(text.length > 200_000 ? text.slice(0, 200_000) : text),
    domain: e.type === "link" ? (linkDomain(text) ?? undefined) : undefined,
    ocr: e.ocrText ? e.ocrText.slice(0, 400) : undefined,
  };
}

/** Host of a link without "www." (null if it does not parse). */
export function linkDomain(text: string): string | null {
  const t = text.trim();
  if (/^mailto:/i.test(t)) return t.slice(7).split("@")[1]?.split(/[?#]/)[0] ?? null;
  try {
    const u = new URL(/^[a-z][a-z0-9+.-]*:/i.test(t) ? t : `https://${t}`);
    return u.hostname ? u.hostname.replace(/^www\./i, "") : null;
  } catch {
    return null;
  }
}

/** URL to open for a link entry ("www.x.com" → "https://www.x.com"). */
export function linkHref(text: string): string {
  const t = text.trim();
  return /^[a-z][a-z0-9+.-]*:/i.test(t) ? t : `https://${t}`;
}

/** "[title](url)" with a title defaulting to the domain; brackets in the title are escaped. */
export function markdownLink(url: string, title?: string): string {
  const href = linkHref(url);
  const label = (title?.trim() || linkDomain(url) || href).replace(/([[\]\\])/g, "\\$1");
  return `[${label}](${href.replace(/\)/g, "%29").replace(/ /g, "%20")})`;
}

/** Text an entry contributes when merged or pasted as text (files → paths). Images contribute nothing. */
export function entryText(e: Pick<ClipEntry, "type" | "text" | "files">): string | null {
  if (e.type === "image") return null;
  if (e.type === "file") return e.files?.length ? e.files.join("\n") : null;
  return e.text ?? null;
}

/**
 * Merge entries into one text, in the given order (the caller passes them oldest-first so
 * the result reads in copy order). Returns null when fewer than one text-bearing entry.
 */
export function mergeTexts(list: Array<Pick<ClipEntry, "type" | "text" | "files">>, separator = "\n"): string | null {
  const parts = list.map(entryText).filter((t): t is string => t !== null && t.length > 0);
  return parts.length ? parts.join(separator) : null;
}

export interface SourceSummary {
  key: string;
  name: string;
  bundleId: string | null;
  count: number;
}

/** Distinct source apps, most entries first. */
export function sourceApps(entries: ClipEntry[]): SourceSummary[] {
  const map = new Map<string, SourceSummary>();
  for (const e of entries) {
    const key = sourceKey(e.source);
    if (!key || !e.source) continue;
    const cur = map.get(key);
    if (cur) cur.count++;
    else map.set(key, { key, name: e.source.name, bundleId: e.source.bundleId, count: 1 });
  }
  return [...map.values()].sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
}

export interface ClipStats {
  total: number;
  pinned: number;
  byType: Record<ClipType, number>;
  imageBytes: number;
  oldest: number | null;
  paused: boolean;
  /** Set while a timed pause is running. */
  pausedUntil: number | null;
  enabled: boolean;
}

export function computeStats(entries: ClipEntry[], s: Pick<ClipSettings, "paused" | "enabled"> & { pausedUntil?: number }, now = Date.now()): ClipStats {
  const byType: Record<ClipType, number> = { text: 0, link: 0, color: 0, file: 0, image: 0 };
  let imageBytes = 0;
  let oldest: number | null = null;
  for (const e of entries) {
    byType[e.type]++;
    imageBytes += e.image?.bytes ?? 0;
    if (oldest === null || e.createdAt < oldest) oldest = e.createdAt;
  }
  const pausedUntil = s.pausedUntil && s.pausedUntil > now ? s.pausedUntil : null;
  return { total: entries.length, pinned: entries.filter((e) => e.pinned).length, byType, imageBytes, oldest, paused: s.paused || pausedUntil !== null, pausedUntil, enabled: s.enabled };
}

/** Coerce settings read from disk into valid values. */
export function normalizeSettings(raw: Partial<ClipSettings>): ClipSettings {
  const d = DEFAULT_CLIP_SETTINGS;
  const num = (v: unknown, def: number, min: number, max: number) => (typeof v === "number" && Number.isFinite(v) ? Math.min(max, Math.max(min, Math.round(v))) : def);
  return {
    enabled: typeof raw.enabled === "boolean" ? raw.enabled : d.enabled,
    paused: typeof raw.paused === "boolean" ? raw.paused : d.paused,
    pausedUntil: num(raw.pausedUntil, 0, 0, Number.MAX_SAFE_INTEGER),
    retentionDays: num(raw.retentionDays, d.retentionDays, 0, 3650),
    retentionByType: normalizeRetentionByType(raw.retentionByType),
    maxEntries: num(raw.maxEntries, d.maxEntries, 10, 100_000),
    maxImages: num(raw.maxImages, d.maxImages, 0, 10_000),
    maxImageMB: num(raw.maxImageMB, d.maxImageMB, 0, 100_000),
    ignoredApps: Array.isArray(raw.ignoredApps) ? raw.ignoredApps.filter((x): x is string => typeof x === "string" && !!x.trim()) : d.ignoredApps,
    hotkey: typeof raw.hotkey === "string" ? raw.hotkey : d.hotkey,
    stackHotkey: typeof raw.stackHotkey === "string" ? raw.stackHotkey : d.stackHotkey,
    stackOrder: raw.stackOrder === "lifo" ? "lifo" : "fifo",
    stackInterceptPaste: raw.stackInterceptPaste === true,
    ocrImages: typeof raw.ocrImages === "boolean" ? raw.ocrImages : d.ocrImages,
    viewMode: raw.viewMode === "grid" ? "grid" : "list",
  };
}

function normalizeRetentionByType(raw: unknown): Partial<Record<ClipType, number>> {
  const out: Partial<Record<ClipType, number>> = {};
  if (!raw || typeof raw !== "object") return out;
  for (const t of CLIP_TYPES) {
    const v = (raw as Record<string, unknown>)[t];
    if (typeof v === "number" && Number.isFinite(v) && v > 0) out[t] = Math.min(3650, Math.round(v));
  }
  return out;
}
