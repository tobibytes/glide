/**
 * Clipboard history data model and pure logic (no Electron, no fs) so it can be unit-tested.
 * The renderer imports these types with `import type`.
 */

export type ClipType = "text" | "link" | "color" | "file" | "image";
export type ClipFilter = "all" | ClipType | "pinned";
export const CLIP_TYPES: ClipType[] = ["text", "image", "link", "file", "color"];
export const CLIP_FILTERS: ClipFilter[] = ["all", "text", "image", "link", "file", "color", "pinned"];

export interface SourceApp {
  name: string;
  bundleId: string | null;
}

export interface ClipImage {
  /** sha1 of the PNG bytes; files live at <dataDir>/images/<sha1>.png and <sha1>.thumb.png */
  sha1: string;
  width: number;
  height: number;
  bytes: number;
}

export interface ClipEntry {
  id: string;
  type: ClipType;
  /** Dedupe key: same key = same content. */
  key: string;
  text?: string;
  files?: string[];
  image?: ClipImage;
  source: SourceApp | null;
  /** First time this content was copied. */
  createdAt: number;
  /** Most recent copy (ordering). */
  lastCopiedAt: number;
  count: number;
  pinned: boolean;
  /** Text recognised in an image (Vision OCR via the helper). undefined = not tried yet, "" = nothing found. */
  ocrText?: string;
}

/** A capture before it becomes an entry. */
export interface ClipCandidate {
  type: ClipType;
  key: string;
  text?: string;
  files?: string[];
  image?: ClipImage;
  source: SourceApp | null;
}

export interface ClipSettings extends Record<string, unknown> {
  enabled: boolean;
  paused: boolean;
  /** epoch ms; recording is paused until then ("Pause for 5 Minutes"). 0 = not timed. */
  pausedUntil: number;
  /** 0 = keep forever */
  retentionDays: number;
  /** Per-type override in days (0 or missing = use retentionDays). */
  retentionByType: Partial<Record<ClipType, number>>;
  maxEntries: number;
  maxImages: number;
  maxImageMB: number;
  ignoredApps: string[];
  /** Electron accelerator or "" */
  hotkey: string;
  /** Global hotkey for "Paste Next from Stack" (Electron accelerator or ""). */
  stackHotkey: string;
  /** Order the paste stack pastes in: first copied first (fifo) or last copied first (lifo). */
  stackOrder: "fifo" | "lifo";
  /** Let plain ⌘V paste the next Paste Stack item. Off by default: a forgotten stack must never hijack paste. */
  stackInterceptPaste: boolean;
  /** Recognise text in copied images (needs the Glide helper) so they are searchable. */
  ocrImages: boolean;
  /** Remembered layout of Clipboard History. */
  viewMode: "list" | "grid";
}

